export function assistantDefectContext(question) {
  if (typeof question !== 'string' || !question.trim()) return null;
  const guide = GUIDES.find(item => item.keywords.some(keyword => question.includes(keyword)));
  if (!guide) return null;
  return [
    `通用缺陷排查建议（${guide.title}）：以下仅为检查方向，不代表项目批准工艺，也不替代工艺文件。`,
    ...guide.checks.map((check, index) => `${index + 1}. ${check}`),
    '引用或调整任何焊接参数前，必须核对当前项目已批准的工艺与质量规则。',
  ].join('\n');
}

