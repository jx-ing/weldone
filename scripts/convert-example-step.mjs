import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
import {stepMeshFromResult} from '../src/stepMesh.mjs';
const require=createRequire(import.meta.url),root=path.resolve(import.meta.dirname,'..');
const input=process.argv[2]||path.join(root,'public/models/111.step');
const content=fs.readFileSync(input),occt=await require('occt-import-js')();
const result=occt.ReadStepFile(content,{linearUnit:'millimeter',linearDeflectionType:'absolute_value',linearDeflection:.12,angularDeflection:.15});
const output=stepMeshFromResult(result,'111.step',crypto.createHash('sha256').update(content).digest('hex'));
const {meshes,edges}=output;
const folder=path.join(root,'public/models');fs.mkdirSync(folder,{recursive:true});
if(path.resolve(input)!==path.join(folder,'111.step'))fs.copyFileSync(input,path.join(folder,'111.step'));
fs.writeFileSync(path.join(folder,'111.mesh.json'),JSON.stringify(output));
console.log(JSON.stringify({name:output.name,parts:meshes.length,edges:edges.length,triangles:meshes.reduce((n,m)=>n+m.indices.length/3,0),size:output.size,sha256:output.sourceSha256}));
